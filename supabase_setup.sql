-- ---------- 8. FUNCIONES PÚBLICAS SEGURAS ----------
-- Valida un código sin exponer la lista de códigos
create or replace function public.sw_validar_codigo(p_codigo text)
returns table (valido boolean, asociacion text, comision_pct numeric)
language sql stable security definer set search_path = public as $$
  select true, c.asociacion, c.comision_pct from public.sw_codigos c
  where c.activo and c.codigo = upper(trim(p_codigo)) limit 1;
$$;

-- Cupos ocupados por sede y taller (cuenta pendientes + confirmados, no rechazados)
create or replace function public.sw_cupos()
returns table (sede_id bigint, taller_id bigint, ocupados bigint)
language sql stable security definer set search_path = public as $$
  select i.sede_id, (e ->> 'taller_id')::bigint, count(*)
  from public.inscripciones_survival i, jsonb_array_elements(coalesce(i.seleccion, '[]'::jsonb)) e
  where i.sede_id is not null and coalesce(i.estado_pago,'pendiente') <> 'rechazado'
  group by 1, 2;
$$;

-- El estudiante consulta su estado con correo + últimos dígitos de su teléfono.
-- Si su pago está confirmado, recibe el link del grupo de WhatsApp de su sede.
create or replace function public.sw_consultar_inscripcion(p_email text, p_telefono text)
returns table (nombres text, sede text, talleres text, estado_pago text, grupo_whatsapp text)
language sql stable security definer set search_path = public as $$
  select i.nombres, coalesce(s.ciudad || coalesce(' · ' || s.lugar, ''), i.sede), i.talleres, coalesce(i.estado_pago,'pendiente'),
         case when i.estado_pago = 'confirmado' then s.grupo_whatsapp end
  from public.inscripciones_survival i
  left join public.sw_sedes s on s.id = i.sede_id
  where lower(trim(i.email)) = lower(trim(p_email))
    and right(regexp_replace(coalesce(i.telefono,''), '\D', '', 'g'), 7) = right(regexp_replace(coalesce(p_telefono,''), '\D', '', 'g'), 7)
    and length(regexp_replace(coalesce(p_telefono,''), '\D', '', 'g')) >= 7
  order by i.id desc limit 5;
$$;

grant execute on function public.sw_validar_codigo(text) to anon, authenticated;
grant execute on function public.sw_cupos() to anon, authenticated;
grant execute on function public.sw_consultar_inscripcion(text, text) to anon, authenticated;
grant execute on function public.is_sw_admin() to anon, authenticated;

