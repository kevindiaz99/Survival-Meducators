-- ---------- 2. SEDES ----------
create table if not exists public.sw_sedes (
  id bigint generated by default as identity primary key,
  ciudad text not null,
  lugar text,                         -- ej. ESPOCH
  aso_aliada text,                    -- ej. ASO de Enfermería UESS
  etapa text,                         -- ej. "Primera etapa"
  fecha_texto text,                   -- ej. "14 y 15 de noviembre"
  fecha_inicio date,                  -- para ordenar
  dia1_label text default 'Sábado',
  dia2_label text default 'Domingo',
  estado text not null default 'por_confirmar' check (estado in ('abierta','por_confirmar','agotada','cerrada')),
  coordinador text,
  coordinador_telefono text,
  grupo_whatsapp text,                -- link de invitación al grupo de la sede
